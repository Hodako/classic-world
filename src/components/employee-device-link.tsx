"use client";

import { useState } from "react";
import { Smartphone, Copy, RefreshCw, KeyRound, Check } from "lucide-react";
import { toast } from "sonner";
import { Button } from "@/components/ui/button";
import { Input } from "@/components/ui/input";
import { Label } from "@/components/ui/label";
import {
  Dialog,
  DialogContent,
  DialogHeader,
  DialogTitle,
  DialogDescription,
} from "@/components/ui/dialog";
import { useT } from "@/lib/i18n";
import type { AuthUser } from "@/hooks/use-auth";
import {
  issueEmployeeDeviceCode,
  redeemEmployeeDeviceCode,
  listEmployeeDevices,
  revokeEmployeeDevice,
  type EmployeeDevice,
} from "@/lib/employee-device-link";

export function EmployeeDeviceCodeForm({
  onLinked,
}: {
  onLinked: (user: AuthUser, token: string) => void;
}) {
  const { lang } = useT();
  const [code, setCode] = useState("");
  const [deviceName, setDeviceName] = useState("");
  const [busy, setBusy] = useState(false);

  return (
    <form
      className="space-y-3 rounded-2xl border border-border/80 bg-card/60 p-4 shadow-sm"
      onSubmit={async (e) => {
        e.preventDefault();
        if (busy) return;
        setBusy(true);
        try {
          const result = await redeemEmployeeDeviceCode(code, deviceName);
          onLinked(result.user, result.token);
        } catch (error) {
          toast.error(error instanceof Error ? error.message : "Device linking failed");
        } finally {
          setBusy(false);
        }
      }}
    >
      <h2 className="text-sm font-semibold flex items-center gap-2">
        <Smartphone className="size-4 text-emerald-600 dark:text-emerald-400" />
        {lang === "bn" ? "ডিভাইস লিংক কোড" : "Link with Device Code"}
      </h2>
      <p className="text-xs text-muted-foreground">
        {lang === "bn"
          ? "দোকান মালিক কর্তৃক প্রদত্ত ডিভাইস কোড দিয়ে এই ডিভাইসটি লিংক করুন।"
          : "Link this terminal using the pairing code generated by your shop owner."}
      </p>
      <div className="space-y-1">
        <Label htmlFor="employee-link-code">{lang === "bn" ? "ডিভাইস কোড" : "Device code"}</Label>
        <Input
          id="employee-link-code"
          required
          value={code}
          onChange={(e) => setCode(e.target.value.toUpperCase())}
          placeholder="CW12-3456-7890"
          autoComplete="one-time-code"
          spellCheck={false}
          maxLength={18}
          className="font-mono font-bold tracking-wider uppercase text-center sm:text-left"
        />
      </div>
      <div className="space-y-1">
        <Label htmlFor="employee-device-name">
          {lang === "bn" ? "ডিভাইসের নাম (ঐচ্ছিক)" : "Device name (optional)"}
        </Label>
        <Input
          id="employee-device-name"
          value={deviceName}
          onChange={(e) => setDeviceName(e.target.value)}
          maxLength={80}
          placeholder={lang === "bn" ? "ক্যাশ কাউন্টার ট্যাবলেট" : "Counter tablet / Mobile"}
        />
      </div>
      <Button
        type="submit"
        disabled={busy || code.replace(/[\s-]/g, "").length < 6}
        className="w-full bg-emerald-600 hover:bg-emerald-700 text-white font-medium"
      >
        {busy ? (
          <RefreshCw className="size-4 animate-spin" />
        ) : lang === "bn" ? (
          "ডিভাইস লিংক করে লগইন করুন"
        ) : (
          "Link Device & Sign In"
        )}
      </Button>
    </form>
  );
}

export function OwnerEmployeeDeviceLink({
  employeeId,
  employeeName,
  employeePin,
  disabled,
}: {
  employeeId: string;
  employeeName: string;
  employeePin?: string;
  disabled?: boolean;
}) {
  const { lang } = useT();
  const [open, setOpen] = useState(false);
  const [busy, setBusy] = useState(false);
  const [issued, setIssued] = useState<{ code: string; expiresAt: number; pin?: string } | null>(null);
  const [copiedCode, setCopiedCode] = useState(false);
  const [copiedPin, setCopiedPin] = useState(false);
  const [devices, setDevices] = useState<EmployeeDevice[]>([]);
  const [error, setError] = useState("");

  const refresh = async () => {
    try {
      const result = await listEmployeeDevices();
      setDevices(result.devices.filter((d) => d.employeeId === employeeId));
    } catch (_) {}
  };

  const activePin = issued?.pin || employeePin || "1234";

  return (
    <>
      <Button
        type="button"
        size="sm"
        variant="outline"
        disabled={disabled}
        className="h-8 gap-1 text-xs"
        onClick={async () => {
          setOpen(true);
          setIssued(null);
          setError("");
          try {
            await refresh();
          } catch (e) {
            setError(e instanceof Error ? e.message : "Unable to load devices");
          }
        }}
      >
        <Smartphone className="size-3.5 text-emerald-600 dark:text-emerald-400" />
        {lang === "bn" ? "ডিভাইস লিংক" : "Link device"}
      </Button>

      <Dialog open={open} onOpenChange={setOpen}>
        <DialogContent className="sm:max-w-md max-h-[90vh] overflow-y-auto">
          <DialogHeader>
            <DialogTitle className="flex items-center gap-2">
              <Smartphone className="size-5 text-emerald-600" />
              {lang === "bn" ? "কর্মচারীর ডিভাইস লিংক ও এক্সেস" : "Employee Device Pairing & PIN"}
            </DialogTitle>
            <DialogDescription>
              {employeeName} ·{" "}
              {lang === "bn"
                ? "কর্মচারী তার ফোন বা কম্পিউটার থেকে এই তথ্য ব্যবহার করে লগইন করবেন।"
                : "The employee can use either the device pairing code or the direct PIN."}
            </DialogDescription>
          </DialogHeader>

          <div className="space-y-4 pt-2">
            {/* Direct PIN Box */}
            <div className="rounded-xl border border-emerald-500/30 bg-emerald-500/10 p-3.5 flex items-center justify-between">
              <div className="space-y-0.5">
                <div className="flex items-center gap-1.5">
                  <KeyRound className="size-3.5 text-emerald-700 dark:text-emerald-400" />
                  <span className="text-xs font-semibold text-emerald-800 dark:text-emerald-300">
                    {lang === "bn" ? "কর্মচারীর সরাসরি পিন (PIN):" : "Direct Staff PIN:"}
                  </span>
                </div>
                <p className="font-mono text-xl font-bold tracking-widest text-emerald-950 dark:text-emerald-100">
                  {activePin}
                </p>
                <p className="text-[11px] text-muted-foreground">
                  {lang === "bn"
                    ? "/employee-login পেজে সরাসরি এই পিন দিয়েও ঢুকতে পারবেন"
                    : "Can sign in directly at /employee-login using this PIN"}
                </p>
              </div>
              <Button
                type="button"
                size="sm"
                variant="outline"
                className="h-8 gap-1.5 text-xs border-emerald-500/40 hover:bg-emerald-500/20"
                onClick={async () => {
                  try {
                    await navigator.clipboard.writeText(activePin);
                    setCopiedPin(true);
                    setTimeout(() => setCopiedPin(false), 2000);
                    toast.success(lang === "bn" ? "পিন কপি হয়েছে" : "PIN copied");
                  } catch {
                    toast.error("Could not copy PIN");
                  }
                }}
              >
                {copiedPin ? <Check className="size-3.5 text-emerald-600" /> : <Copy className="size-3.5" />}
                {copiedPin ? (lang === "bn" ? "কপি হয়েছে" : "Copied") : (lang === "bn" ? "কপি পিন" : "Copy")}
              </Button>
            </div>

            {/* Generate Pairing Code */}
            <div className="space-y-3">
              <Button
                type="button"
                disabled={busy}
                className="w-full bg-emerald-600 hover:bg-emerald-700 text-white"
                onClick={async () => {
                  setBusy(true);
                  setError("");
                  try {
                    const res = await issueEmployeeDeviceCode(employeeId);
                    setIssued(res);
                    toast.success(lang === "bn" ? "ডিভাইস কোড তৈরি হয়েছে!" : "Device code generated!");
                  } catch (e) {
                    setError(e instanceof Error ? e.message : "Unable to generate code");
                  } finally {
                    setBusy(false);
                  }
                }}
              >
                {busy ? (
                  <RefreshCw className="size-4 animate-spin mr-2" />
                ) : (
                  <Smartphone className="size-4 mr-2" />
                )}
                {lang === "bn" ? "নতুন ডিভাইস পেয়ারিং কোড তৈরি করুন" : "Generate Device Pairing Code"}
              </Button>

              {issued && (
                <div className="space-y-2 rounded-xl border border-primary/40 bg-primary/5 p-4 text-center">
                  <p className="text-xs text-muted-foreground">
                    {lang === "bn"
                      ? "কর্মচারী তার ব্রাউজারে /employee-login বা /auth পেজে এই কোডটি লিখবেন:"
                      : "Staff can enter this 1-time code at /employee-login or /auth:"}
                  </p>
                  <p
                    className="font-mono text-2xl font-black tracking-widest text-primary break-all py-1 select-all"
                    aria-live="polite"
                  >
                    {issued.code}
                  </p>
                  <p className="text-xs text-muted-foreground">
                    {lang === "bn" ? "মেয়াদ:" : "Expires:"}{" "}
                    {new Date(issued.expiresAt).toLocaleTimeString()} (২৪ ঘণ্টা কার্যকর)
                  </p>
                  <Button
                    type="button"
                    size="sm"
                    variant="outline"
                    className="gap-2 mx-auto"
                    onClick={async () => {
                      try {
                        await navigator.clipboard.writeText(issued.code);
                        setCopiedCode(true);
                        setTimeout(() => setCopiedCode(false), 2000);
                        toast.success(lang === "bn" ? "কোড কপি হয়েছে" : "Code copied");
                      } catch {
                        toast.error("Select and copy the code above.");
                      }
                    }}
                  >
                    {copiedCode ? <Check className="size-3.5 text-emerald-600" /> : <Copy className="size-3.5" />}
                    {copiedCode ? (lang === "bn" ? "কপি হয়েছে" : "Copied") : (lang === "bn" ? "কোড কপি করুন" : "Copy Code")}
                  </Button>
                </div>
              )}
            </div>

            {error && (
              <p role="alert" className="text-sm text-destructive bg-destructive/10 p-2.5 rounded-lg">
                {error}
              </p>
            )}

            {/* Linked Devices List */}
            <div className="space-y-2 pt-2 border-t border-border">
              <div className="flex items-center justify-between">
                <h3 className="text-sm font-semibold">
                  {lang === "bn" ? "লিংক করা ডিভাইসসমূহ" : "Linked devices"}
                </h3>
                <Button
                  type="button"
                  size="sm"
                  variant="ghost"
                  className="h-7 text-xs"
                  onClick={() => refresh().catch((e) => setError(e.message))}
                >
                  <RefreshCw className="size-3 mr-1" />
                  {lang === "bn" ? "রিফ্রেশ" : "Refresh"}
                </Button>
              </div>
              {devices.length === 0 && (
                <p className="text-xs text-muted-foreground">
                  {lang === "bn" ? "এখনো কোনো ডিভাইস লিংক করা হয়নি।" : "No devices linked yet."}
                </p>
              )}
              {devices.map((d) => (
                <div
                  key={d.id}
                  className="flex items-center justify-between gap-2 border-t border-border/50 py-2"
                >
                  <div className="text-xs">
                    <p className="font-medium text-foreground">{d.name}</p>
                    <p className="text-muted-foreground text-[10px]">
                      {new Date(d.linkedAt).toLocaleDateString()} {new Date(d.linkedAt).toLocaleTimeString()}
                    </p>
                  </div>
                  <Button
                    type="button"
                    variant="outline"
                    size="sm"
                    className="h-7 text-xs text-destructive hover:bg-destructive/10"
                    disabled={busy}
                    onClick={async () => {
                      setBusy(true);
                      try {
                        await revokeEmployeeDevice(d.id);
                        await refresh();
                        toast.success(lang === "bn" ? "ডিভাইস আনলিংক করা হয়েছে" : "Device unlinked");
                      } catch (e) {
                        setError(e instanceof Error ? e.message : "Unable to unlink");
                      } finally {
                        setBusy(false);
                      }
                    }}
                  >
                    {lang === "bn" ? "আনলিংক" : "Unlink"}
                  </Button>
                </div>
              ))}
            </div>
          </div>
        </DialogContent>
      </Dialog>
    </>
  );
}
